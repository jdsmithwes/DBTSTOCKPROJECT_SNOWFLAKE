with stock_prices as (
    select
        ticker,
        date,
        open,
        high,
        low,
        close,
        adjusted_close,
        volume,
        dividend_amount,
        split_coefficient
    from {{ ref('stg_stockprice') }}
),

company as (
    select
        ticker,
        company_name,
        asset_type,
        exchange,
        currency,
        country,
        sector,
        address,
        official_site,
        description,
        cik,
        fiscal_year_end,
        dividend_date,
        ex_dividend_date,
        latest_quarter,
        ma_50d,
        ma_200d,
        week_52_high,
        week_52_low,
        pe_ratio,
        trailing_pe,
        forward_pe,
        peg_ratio,
        price_to_book_ratio,
        price_to_sales_ratio_ttm,
        ev_to_ebitda,
        ev_to_revenue,
        beta,
        profit_margin,
        operating_margin_ttm,
        return_on_assets_ttm,
        return_on_equity_ttm,
        quarterly_earnings_growth_yoy,
        quarterly_revenue_growth_yoy,
        revenue_ttm,
        revenue_per_share_ttm,
        gross_profit_ttm,
        ebitda,
        eps,
        diluted_eps_ttm,
        book_value,
        dividend_per_share,
        dividend_yield,
        market_capitalization,
        shares_outstanding,
        shares_float,
        percent_insiders,
        percent_institutions,
        analyst_rating_strong_buy,
        analyst_rating_buy,
        analyst_rating_hold,
        analyst_rating_sell,
        analyst_rating_strong_sell,
        analyst_target_price
    from {{ ref('stg_companyoverview') }}
    qualify row_number() over (partition by ticker order by ingest_timestamp desc) = 1
),

mapping as (
    select
        company_industry,
        indicator_industry
    from {{ ref('int_industry_mapping') }}
),

indicators as (
    select
        name as indicator_name,
        classification as indicator_classification,
        units as indicator_units,
        industrylist as indicator_industrylist,
        value as indicator_value,
        date as indicator_date
    from {{ ref('industry_indicators_descriptions') }}
),

indicators_exploded as (
    select
        indicators.indicator_name,
        indicators.indicator_classification,
        indicators.indicator_units,
        indicators.indicator_value,
        indicators.indicator_date,
        trim(f.value::string) as indicator_industry
    from indicators,
        lateral flatten(input => split(indicators.indicator_industrylist, ',')) as f
),

stock_with_company as (
    select
        sp.ticker,
        sp.date,
        sp.open,
        sp.high,
        sp.low,
        sp.close,
        sp.adjusted_close,
        sp.volume,
        sp.dividend_amount,
        sp.split_coefficient,
        co.company_name,
        co.asset_type,
        co.exchange,
        co.currency,
        co.country,
        co.sector,
        co.address,
        co.official_site,
        co.description,
        co.cik,
        co.fiscal_year_end,
        co.dividend_date,
        co.ex_dividend_date,
        co.latest_quarter,
        co.ma_50d,
        co.ma_200d,
        co.week_52_high,
        co.week_52_low,
        co.pe_ratio,
        co.trailing_pe,
        co.forward_pe,
        co.peg_ratio,
        co.price_to_book_ratio,
        co.price_to_sales_ratio_ttm,
        co.ev_to_ebitda,
        co.ev_to_revenue,
        co.beta,
        co.profit_margin,
        co.operating_margin_ttm,
        co.return_on_assets_ttm,
        co.return_on_equity_ttm,
        co.quarterly_earnings_growth_yoy,
        co.quarterly_revenue_growth_yoy,
        co.revenue_ttm,
        co.revenue_per_share_ttm,
        co.gross_profit_ttm,
        co.ebitda,
        co.eps,
        co.diluted_eps_ttm,
        co.book_value,
        co.dividend_per_share,
        co.dividend_yield,
        co.market_capitalization,
        co.shares_outstanding,
        co.shares_float,
        co.percent_insiders,
        co.percent_institutions,
        co.analyst_rating_strong_buy,
        co.analyst_rating_buy,
        co.analyst_rating_hold,
        co.analyst_rating_sell,
        co.analyst_rating_strong_sell,
        co.analyst_target_price,
        m.indicator_industry as mapped_indicator_industry
    from stock_prices as sp
    inner join company as co on sp.ticker = co.ticker
    left join mapping as m on upper(co.sector) = m.company_industry
)

select
    swc.ticker,
    swc.date,
    swc.open,
    swc.high,
    swc.low,
    swc.close,
    swc.adjusted_close,
    swc.volume,
    swc.dividend_amount,
    swc.split_coefficient,
    swc.company_name,
    swc.asset_type,
    swc.exchange,
    swc.currency,
    swc.country,
    swc.sector,
    swc.address,
    swc.official_site,
    swc.description,
    swc.cik,
    swc.fiscal_year_end,
    swc.dividend_date,
    swc.ex_dividend_date,
    swc.latest_quarter,
    swc.ma_50d,
    swc.ma_200d,
    swc.week_52_high,
    swc.week_52_low,
    swc.pe_ratio,
    swc.trailing_pe,
    swc.forward_pe,
    swc.peg_ratio,
    swc.price_to_book_ratio,
    swc.price_to_sales_ratio_ttm,
    swc.ev_to_ebitda,
    swc.ev_to_revenue,
    swc.beta,
    swc.profit_margin,
    swc.operating_margin_ttm,
    swc.return_on_assets_ttm,
    swc.return_on_equity_ttm,
    swc.quarterly_earnings_growth_yoy,
    swc.quarterly_revenue_growth_yoy,
    swc.revenue_ttm,
    swc.revenue_per_share_ttm,
    swc.gross_profit_ttm,
    swc.ebitda,
    swc.eps,
    swc.diluted_eps_ttm,
    swc.book_value,
    swc.dividend_per_share,
    swc.dividend_yield,
    swc.market_capitalization,
    swc.shares_outstanding,
    swc.shares_float,
    swc.percent_insiders,
    swc.percent_institutions,
    swc.analyst_rating_strong_buy,
    swc.analyst_rating_buy,
    swc.analyst_rating_hold,
    swc.analyst_rating_sell,
    swc.analyst_rating_strong_sell,
    swc.analyst_target_price,
    swc.mapped_indicator_industry,
    ie.indicator_name,
    ie.indicator_classification,
    ie.indicator_units,
    ie.indicator_value,
    ie.indicator_date
from stock_with_company as swc
left join indicators_exploded as ie
    on
        swc.mapped_indicator_industry = ie.indicator_industry
        and swc.date = ie.indicator_date
